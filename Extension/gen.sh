#!/bin/bash
# Writes the extension's main.js from PageAgent.mainSource, so the page hooks have one source.
set -euo pipefail
cd "$(dirname "$0")"
out="Safari MCP Bridge/Safari MCP Bridge Extension/Resources/main.js"
{
  echo "// Generated by Extension/gen.sh from PageAgent.mainSource in Sources/safari-mcp/PageAgent.swift. Do not edit."
  awk '/static let mainSource = #"""/{f=1;next} /^    """#/{f=0} f' ../Sources/safari-mcp/PageAgent.swift | sed 's/^    //'
} > "$out"
node --check "$out" 2>/dev/null || { command -v node >/dev/null && { echo "main.js does not parse" >&2; exit 1; }; }
